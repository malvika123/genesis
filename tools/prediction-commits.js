// Genesis — links each research-log entry to the commit that first held its prediction (Fable's F20). For every data/findings/NN-name/
// folder with a prediction-written-before file, finds the commit that added it (git log --diff-filter=A) and its date, and writes
// docs/PREDICTIONS.md. The commit date shows the prediction came before the result: the entry's own commit is later.
// Usage: node tools/prediction-commits.js
// Copyright (c) 2026 Malvika Sen. MIT License.
const fs = require('fs'),
  cp = require('child_process'),
  path = require('path');
const root = path.join(__dirname, '..'),
  dir = path.join(root, 'data/findings'),
  repo = 'https://github.com/malvika123/genesis';
const git = (args) => cp.execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
const rows = [];
for (const d of fs.readdirSync(dir).sort()) {
  const m = d.match(/^(\d+)-(.+)$/);
  if (!m) continue;
  const f = fs.readdirSync(path.join(dir, d)).find((x) => x.startsWith('prediction-written-before'));
  if (!f) continue;
  const rel = `data/findings/${d}/${f}`,
    out = git(['log', '--diff-filter=A', '--follow', '--format=%H|%h|%cs', '--', rel]).split('\n').filter(Boolean).pop();
  if (!out) continue; // not yet committed
  const [full, short, date] = out.split('|');
  rows.push({ n: +m[1], name: m[2], rel, full, short, date });
}
rows.sort((a, b) => a.n - b.n);
const lines = [
  '# Predictions and the commits that hold them',
  '',
  'Generated by `node tools/prediction-commits.js` (do not edit by hand). Every research-log entry that has a `prediction-written-before` file is listed with the commit',
  'that first added it and that commit\'s date, so anyone can check with `git show COMMIT` that the prediction was written before the result. Entries without a file',
  'either have no prediction file (older entries, before the rule) or were measuring only.',
  '',
  '| Entry | Folder | Prediction commit | Date |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.n} | [${r.name}](../data/findings/${r.n < 10 ? '0' + r.n : r.n}-${r.name}/) | [\`${r.short}\`](${repo}/commit/${r.full}) | ${r.date} |`),
  '',
];
fs.writeFileSync(path.join(root, 'docs/PREDICTIONS.md'), lines.join('\n'));
console.log(rows.length + ' predictions linked');
